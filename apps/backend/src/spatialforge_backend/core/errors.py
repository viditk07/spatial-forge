"""Stable application error contracts."""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum


class ErrorCode(StrEnum):
    """Stable error codes exposed to clients and diagnostic reports."""

    INSUFFICIENT_IMAGES = "INSUFFICIENT_IMAGES"
    INSUFFICIENT_OVERLAP = "INSUFFICIENT_OVERLAP"
    EXCESSIVE_BLUR = "EXCESSIVE_BLUR"
    MIXED_FOCAL_LENGTHS = "MIXED_FOCAL_LENGTHS"
    LOW_FEATURE_DENSITY = "LOW_FEATURE_DENSITY"
    MOVING_SCENE = "MOVING_SCENE"
    UNSUPPORTED_IMAGE_FORMAT = "UNSUPPORTED_IMAGE_FORMAT"
    INSUFFICIENT_RAM = "INSUFFICIENT_RAM"
    INSUFFICIENT_STORAGE = "INSUFFICIENT_STORAGE"
    CUDA_UNAVAILABLE = "CUDA_UNAVAILABLE"
    GPU_UNSUPPORTED = "GPU_UNSUPPORTED"
    DRIVER_ERROR = "DRIVER_ERROR"
    PROCESS_RESOURCE_LIMIT = "PROCESS_RESOURCE_LIMIT"
    FEATURE_EXTRACTION_FAILED = "FEATURE_EXTRACTION_FAILED"
    MATCHING_FAILED = "MATCHING_FAILED"
    TOO_FEW_REGISTERED_IMAGES = "TOO_FEW_REGISTERED_IMAGES"
    DISCONNECTED_CAMERA_GROUPS = "DISCONNECTED_CAMERA_GROUPS"
    DENSE_RECONSTRUCTION_FAILED = "DENSE_RECONSTRUCTION_FAILED"
    EMPTY_POINT_CLOUD = "EMPTY_POINT_CLOUD"
    MESH_GENERATION_FAILED = "MESH_GENERATION_FAILED"
    TEXTURE_GENERATION_FAILED = "TEXTURE_GENERATION_FAILED"
    EXPORT_FAILED = "EXPORT_FAILED"
    DEPENDENCY_MISSING = "DEPENDENCY_MISSING"
    PROJECT_CORRUPTED = "PROJECT_CORRUPTED"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    PATH_INVALID = "PATH_INVALID"
    PROCESS_INTERRUPTED = "PROCESS_INTERRUPTED"
    DATABASE_ERROR = "DATABASE_ERROR"


@dataclass
class AppError(Exception):
    """A classified error safe to translate into an API response."""

    code: ErrorCode
    title: str
    explanation: str
    recommended_action: str
    technical_details: str = ""
    log_file: str | None = None
    retry_safe: bool = False
